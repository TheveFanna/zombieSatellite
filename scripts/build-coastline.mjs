// One-off script: node scripts/build-coastline.mjs <ne_110m_coastline.geojson>
// Source: Natural Earth 1:110m coastline (public domain),
// https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_coastline.geojson
// Output: src/lib/field/data/coastline.ts (SVG path data, x = lon, y = -lat, M absolute, l relative).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_BYTES = 40 * 1024;
const input = process.argv[2];
if (!input) {
  console.error('usage: node scripts/build-coastline.mjs <ne_110m_coastline.geojson>');
  process.exit(1);
}
const geo = JSON.parse(readFileSync(input, 'utf8'));

const lines = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === 'LineString') lines.push(g.coordinates);
  else if (g.type === 'MultiLineString') lines.push(...g.coordinates);
}

function rdp(pts, tol) {
  if (pts.length < 3) return pts;
  const [ax, ay] = pts[0];
  const [bx, by] = pts[pts.length - 1];
  const dx = bx - ax;
  const dy = by - ay;
  const len = Math.hypot(dx, dy);
  let idx = -1;
  let max = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [px, py] = pts[i];
    const d = len === 0 ? Math.hypot(px - ax, py - ay) : Math.abs(dx * (ay - py) - (ax - px) * dy) / len;
    if (d > max) {
      max = d;
      idx = i;
    }
  }
  if (max <= tol) return [pts[0], pts[pts.length - 1]];
  return [...rdp(pts.slice(0, idx + 1), tol).slice(0, -1), ...rdp(pts.slice(idx), tol)];
}

const fmt = (t) => {
  const s = (t / 10).toFixed(1).replace(/\.0$/, '');
  return s.replace(/^(-?)0\./, '$1.');
};

function build(tol) {
  let d = '';
  for (const line of lines) {
    const s = rdp(line, tol).map(([lon, lat]) => [Math.round(lon * 10), Math.round(-lat * 10)]);
    const q = s.filter((p, i) => i === 0 || p[0] !== s[i - 1][0] || p[1] !== s[i - 1][1]);
    if (q.length < 2) continue;
    d += `M${fmt(q[0][0])} ${fmt(q[0][1])}`;
    for (let i = 1; i < q.length; i++) {
      const dx = q[i][0] - q[i - 1][0];
      const dy = q[i][1] - q[i - 1][1];
      const sy = fmt(dy);
      d += `l${fmt(dx)}${sy.startsWith('-') ? '' : ' '}${sy}`;
    }
  }
  return d;
}

function render(d, tol) {
  return `// Natural Earth 1:110m coastline (ne_110m_coastline), public domain.
// Source: https://www.naturalearthdata.com/ (terms: https://www.naturalearthdata.com/about/terms-of-use/)
// Generated by scripts/build-coastline.mjs, RDP tolerance ${tol.toFixed(2)} deg, quantized to 0.1 deg.
// Map units: x = lon, y = -lat. Source and licence are recorded in docs/reference/MODELS.md later.
export const COASTLINE_PATH: string =
  '${d}';
`;
}

let tol = 0.25;
let out = render(build(tol), tol);
while (Buffer.byteLength(out) > MAX_BYTES) {
  tol = Math.round((tol + 0.05) * 100) / 100;
  out = render(build(tol), tol);
}
const target = fileURLToPath(new URL('../src/lib/field/data/coastline.ts', import.meta.url));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`tolerance ${tol}, ${Buffer.byteLength(out)} bytes -> ${target}`);
